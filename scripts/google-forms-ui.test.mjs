import assert from "node:assert/strict";
import { test } from "node:test";
import { spawn } from "node:child_process";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";

test("desktop and mobile forms UI: draft, edit, approve, mirror and no horizontal overflow", { timeout: 90_000 }, async () => {
  const server = spawn(process.execPath, ["scripts/google-forms-ui-server.mjs"], { env: { ...process.env, GOOGLE_FORMS_UI_PORT: "3333" }, stdio: ["ignore", "pipe", "pipe"] });
  let browser;
  try {
    await new Promise((resolve, reject) => {
      const timeout = setTimeout(() => reject(new Error("Fixture startup timed out")), 20_000);
      server.stdout.on("data", (chunk) => { if (String(chunk).includes("UI fixture:")) { clearTimeout(timeout); resolve(); } });
      server.once("exit", (code) => { clearTimeout(timeout); reject(new Error(`Fixture exited ${code}`)); });
    });
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ locale: "ko-KR", viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://127.0.0.1:3333");
    await page.getByRole("heading", { name: "Application management" }).waitFor();
    await page.getByLabel("행사 계획", { exact: true }).fill("외국인과 함께하는 명상 프로그램 만들기");
    await page.getByRole("button", { name: "행사 기획", exact: true }).click();
    const answer = async (label, value) => {
      await page.getByLabel(label, { exact: true }).fill(value);
      await page.getByRole("button", { name: "답변 보내기", exact: true }).click();
    };
    await answer("진행 날짜", "2026-11-20");
    await answer("모집 인원", "30");
    await page.reload();
    await page.getByLabel("저장된 행사", { exact: true }).selectOption("fixture-studio-job");
    await answer("진행 장소", "Test Culture Center");
    await answer("신청 마감", "2026-11-21");
    await page.getByRole("alert").getByText(/신청 마감은 행사 일시보다 늦을 수 없습니다/).waitFor();
    await answer("신청 마감", "2026-11-19");
    await page.getByLabel("제목", { exact: true }).waitFor();
    assert.match(await page.getByLabel("한국어 공지", { exact: true }).inputValue(), /문화교류/);
    assert.match(await page.getByLabel("한국어 공지", { exact: true }).inputValue(), /Test Culture Center/);
    assert.equal(await page.getByRole("button", { name: "승인 · 비공개 폼 생성", exact: true }).isEnabled(), true);
    assert.equal(await page.getByRole("tab", { name: "우혁몬 5.0", exact: true }).getAttribute("aria-selected"), "true");
    await page.getByRole("tab", { name: "Google Forms", exact: true }).click();
    await page.getByLabel("활동 제목", { exact: true }).fill("ECC Gathering UI Test");
    assert.equal(await page.getByLabel("Activity date", { exact: true }).count(), 0);
    assert.equal(await page.getByLabel("Deadline", { exact: true }).count(), 0);
    assert.equal(await page.getByLabel("Location", { exact: true }).count(), 0);
    await page.getByRole("button", { name: "신청폼 · 공지 생성", exact: true }).click();
    await answer("진행 날짜", "2026-11-20");
    await answer("모집 인원", "30");
    await answer("진행 장소", "Test Culture Center");
    await answer("신청 마감", "2026-11-19");
    await page.getByRole("button", { name: "확인 · 신청폼 · 공지 생성", exact: true }).click();
    await page.getByRole("button", { name: "생성 완료", exact: true }).waitFor();
    const notice = await page.getByLabel("생성된 공지문").inputValue();
    assert.match(notice, /ECC Gathering UI Test/);
    assert.equal(notice.includes("https://docs.google.com/forms/d/e/test-fixture/viewform"), false);
    assert.equal(await page.getByLabel("신청 링크", { exact: true }).inputValue(), "https://docs.google.com/forms/d/e/test-fixture/viewform");
    assert.equal(notice.includes("{{GOOGLE_FORM_URL}}"), false);
    await mkdir("artifacts/google-forms", { recursive: true });
    await page.screenshot({ path: "artifacts/google-forms/desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole("tab", { name: "신청자 관리", exact: true }).click();
    await page.getByRole("button", { name: "조 자동 편성 및 공지문 생성", exact: true }).click();
    await page.getByText("Test Participant", { exact: true }).waitFor();
    assert.equal(await page.getByText("Friday, Saturday", { exact: true }).count(), 0);
    assert.equal(await page.getByText("person@example.test", { exact: true }).count(), 0);
    assert.match(await page.getByLabel("조 편성 공지문").inputValue(), /Test Participant/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: "artifacts/google-forms/mobile.png", fullPage: true });
    await page.getByRole("button", { name: "Close", exact: true }).click();
    await page.getByRole("button", { name: "행사 삭제", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "삭제", exact: true }).isEnabled(), false);
    await page.getByRole("button", { name: "취소", exact: true }).click();
    assert.equal(await page.getByRole("heading", { name: "ECC Gathering UI Test", exact: true }).count(), 1);
    await page.getByRole("button", { name: "행사 삭제", exact: true }).click();
    await page.getByRole("checkbox", { name: "행사가 종료되었음을 확인했습니다.", exact: true }).check();
    await page.getByRole("button", { name: "삭제", exact: true }).click();
    await page.getByText("No Google Form is registered for this club.", { exact: true }).waitFor();
    const response = await page.request.get("http://127.0.0.1:3333/api/google-forms/forms/fixture-form/responses");
    assert.equal((await response.json()).responses.length, 1);
    await page.screenshot({ path: "artifacts/google-forms/deleted-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: "artifacts/google-forms/deleted-desktop.png", fullPage: true });
    await page.getByRole("button", { name: "EN", exact: true }).click();
    await page.getByRole("tab", { name: "WOOHYUKMON 5.0", exact: true }).click();
    await page.getByLabel("Event request", { exact: true }).fill("Create a meditation program");
    await page.getByRole("button", { name: "Plan event", exact: true }).click();
    await page.getByText(/When would you like to hold/).waitFor();
    await page.getByLabel("Event date", { exact: true }).fill("2026-11-20");
    await page.getByRole("button", { name: "Send answer", exact: true }).click();
    await page.getByText("How many participants would you like to recruit?", { exact: true }).waitFor();
    await page.screenshot({ path: "artifacts/google-forms/english-question.png", fullPage: true });
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close(); server.kill("SIGTERM");
    if (server.exitCode === null) await new Promise((resolve) => server.once("exit", resolve));
  }
});
